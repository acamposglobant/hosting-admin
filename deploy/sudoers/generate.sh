#!/usr/bin/env bash
# Generates /etc/sudoers.d/hostingadmin-agent content for a given unit list
# (increment 2, D16 / plan §3.2, TA14).
#
# Usage:
#   ./generate.sh nginx.service ssh.service > hostingadmin-agent
#   visudo -cf hostingadmin-agent   # ALWAYS validate before installing
#
# The unit list must match Services:UnitNames in the API's appsettings.json.
# Every line is a complete fixed command line: no wildcards, no variables.
# The agent account can run exactly the enumerated commands and nothing more.

set -euo pipefail

if [ "$#" -eq 0 ]; then
    echo "usage: $0 UNIT [UNIT...]" >&2
    exit 2
fi

cat <<'HEADER'
# /etc/sudoers.d/hostingadmin-agent — managed file, exact lines only.
# Generated by deploy/sudoers/generate.sh — do not edit by hand.
# One line per allowlisted unit x action; no wildcards, no variables.
HEADER

for unit in "$@"; do
    # Defensive: unit names are systemd unit names (letters, digits, . _ @ -).
    # Reject anything else rather than emitting a malformed sudoers line.
    if ! [[ "$unit" =~ ^[A-Za-z0-9._@-]+$ ]]; then
        echo "refusing suspicious unit name: $unit" >&2
        exit 1
    fi
    for action in start stop restart; do
        printf 'hostingadmin-agent ALL=(root) NOPASSWD: /usr/bin/systemctl %s %s\n' \
            "$action" "$unit"
    done
done
